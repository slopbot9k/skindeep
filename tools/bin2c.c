/* bin2c: files as a C array of sk_embedded_file (src/base/embed.h),
 * for the build to compile into the program.
 *
 *   bin2c NAME FILE...  > out.c
 *
 * writes NAME[] in the order the files are given, and NAME_count. It
 * runs on the build machine, so it uses nothing but the C library. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *base(const char *path)
{
    const char *slash = strrchr(path, '/');
    return slash ? slash + 1 : path;
}

int main(int argc, char **argv)
{
    if (argc < 3) {
        fprintf(stderr, "usage: bin2c NAME FILE...\n");
        return 2;
    }
    const char *name = argv[1];
    unsigned long *sizes = calloc((size_t)argc, sizeof *sizes);
    if (!sizes)
        return 1;
    printf("/* Generated by tools/bin2c. Do not edit. */\n#include \"src/base/embed.h\"\n\n");
    for (int i = 2; i < argc; i++) {
        FILE *f = fopen(argv[i], "rb");
        if (!f) {
            perror(argv[i]);
            return 1;
        }
        printf("/* %s */\nstatic const uint8_t data_%d[] = {", argv[i], i - 2);
        unsigned long n = 0;
        int c;
        while ((c = getc(f)) != EOF) {
            printf("%s%d,", n % 32 ? "" : "\n", c);
            n++;
        }
        if (ferror(f)) {
            perror(argv[i]);
            return 1;
        }
        fclose(f);
        sizes[i] = n;
        /* An empty file still makes a valid array, of size 0 all the same. */
        printf("%s};\n\n", n ? "" : "0");
    }
    printf("const sk_embedded_file %s[] = {\n", name);
    for (int i = 2; i < argc; i++)
        printf("    {\"%s\", data_%d, %luu},\n", base(argv[i]), i - 2, sizes[i]);
    printf("};\nconst size_t %s_count = %d;\n", name, argc - 2);
    if (fflush(stdout) != 0 || ferror(stdout)) {
        perror("bin2c");
        return 1;
    }
    return 0;
}
