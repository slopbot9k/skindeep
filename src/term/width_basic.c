static int in(uint32_t cp, const range *r, size_t n)
{
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (cp > r[mid].hi)
            lo = mid + 1;
        else if (cp < r[mid].lo)
            hi = mid;
        else
            return 1;
    }
    return 0;
}

int sk_term_wcwidth(uint32_t cp)
{
    if (cp < 32)
        return 0;
    if (cp < 127)
        return 1;
    if (cp < 0xA0)
        return 0;
    if (in(cp, zero, sizeof zero / sizeof zero[0]))
        return 0;
    if (in(cp, wide, sizeof wide / sizeof wide[0]))
        return 2;
    return 1;
}
